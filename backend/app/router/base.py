from typing import Protocol


class RouterError(RuntimeError):
    """Only fixed, safe user-facing messages; never forward router/transport exceptions."""


class RouterOffline(RouterError):
    pass


class RouterAdapter(Protocol):
    url: str
    def inspect(self) -> dict: ...
    def plan(self, inspected: dict, filter_host: str, port: int, name: str) -> dict: ...
    def apply(self, plan: dict) -> None: ...
    def verify(self, plan: dict) -> None: ...
    def confirm(self) -> None: ...
    def restore(self, plan: dict) -> None: ...
    def close(self) -> None: ...
